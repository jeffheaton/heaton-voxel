#!/usr/bin/env python3
"""Write which sides of every block are full into both twins of the library.

A fence, a wall, a pane or iron bars joins a neighbor whose face toward it is
full: the game's ``isFaceSturdy``, ``SupportType.FULL``. That was a hand-kept
list of name endings, which missed every copper block, smooth quartz, stems,
concrete powder and more, so the first city's copper tower stood with every
pane stopping short of its piers (2026-11-01). The face is a fact of the game,
so this is a table of it, as ``wall_cover`` is.

``tools/probe_block_shapes.py`` already reads every state's faces out of the
jar, into ``heaton_voxel/craft/block_facts.py``, and the lower tier may not
import ``craft``, so this copies them down, from one run, into:

    heaton_voxel/connect_faces.py
    csharp/HeatonVoxel/ConnectFaces.generated.cs

Both are derived; edit neither by hand. ``heaton_voxel.connect`` is the
reference for how the table is *used*. A stair is left out: its ``shape`` is
derived in the same sweep as what joins it, so it is read by its ``facing``.
``tests/test_connect.py`` regenerates both files and fails if the committed ones
differ, so rerun this after the probe. It needs no game: the probe has asked
already.

Usage::

    python tools/generate_connect_faces.py
"""

from __future__ import annotations

import itertools
import os
import sys
import textwrap

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from heaton_voxel.craft.block_facts import (  # noqa: E402
    DATA_VERSION,
    FACES,
    facts,
    GAME_VERSION,
)
from heaton_voxel.craft.block_registry import BLOCK_IDS, properties_of  # noqa: E402

PYTHON_OUT = os.path.join(REPO_ROOT, "heaton_voxel", "connect_faces.py")
CSHARP_OUT = os.path.join(REPO_ROOT, "csharp", "HeatonVoxel",
                          "ConnectFaces.generated.cs")

#: The four sides, each a bit, in the table's own order.
SIDES = ("north", "south", "west", "east")


def sides_of(name: str, properties: dict) -> int:
    """The sides of a state that are full, as a mask of :data:`SIDES`."""
    sturdy = facts(name, properties).sturdy
    return sum(1 << bit for bit, side in enumerate(SIDES)
               if sturdy >> FACES.index(side) & 1)


def read_block(name: str):
    """A block as the table holds it: its one mask, or ``(properties,
    {values: mask})`` with only the properties its sides turn on."""
    options = properties_of(name)
    keys = sorted(options)
    states = {values: sides_of(name, dict(zip(keys, values)))
              for values in itertools.product(*(options[k] for k in keys))}
    masks = set(states.values())
    if len(masks) == 1:
        return masks.pop()
    kept = list(range(len(keys)))
    for drop in range(len(keys) - 1, -1, -1):
        rest = [index for index in kept if index != drop]
        seen: dict = {}
        if all(seen.setdefault(tuple(values[i] for i in rest), mask) == mask
               for values, mask in states.items()):
            kept = rest
    table = {tuple(values[i] for i in kept): mask
             for values, mask in states.items()}
    return tuple(keys[i] for i in kept), dict(sorted(table.items()))


def tables() -> tuple:
    """``(whole, sides, by_state)``: blocks full on all four sides in every
    state; blocks with one set of full sides, not all; and blocks read by
    state. A block with no full side in any state is in none of them."""
    whole, sides, by_state = [], {}, {}
    for name in sorted(BLOCK_IDS):
        if name.endswith("_stairs"):
            continue
        read = read_block(name)
        if read == 15:
            whole.append(name)
        elif isinstance(read, int):
            if read:
                sides[name] = read
        else:
            by_state[name] = read
    return whole, sides, by_state


def _summary(whole, sides, by_state) -> str:
    return (f"Generated by tools/generate_connect_faces.py from Minecraft "
            f"{GAME_VERSION}\n(DataVersion {DATA_VERSION}): {len(whole)} blocks "
            f"full all round, {len(sides)} with some\nsides and {len(by_state)} "
            f"read by state. Regenerate rather than edit; both twins\nare "
            f"written by the same run.")


def python_text(whole, sides, by_state) -> str:
    lines = ['"""Which sides of a block are full. GENERATED.', "",
             _summary(whole, sides, by_state), "",
             "What a fence, a wall, a pane or iron bars joins is a neighbor "
             "whose face toward",
             "it is full (the game's ``isFaceSturdy``, "
             "``SupportType.FULL``), and which blocks",
             "the game excepts from that is :mod:`heaton_voxel.connect`'s. "
             "A stair is not here:",
             "it is read by its ``facing``. A name not here has no full side, "
             "as an unknown",
             'block is taken to.', '"""', "",
             "from __future__ import annotations", "",
             "from .block_defaults import BLOCK_DEFAULTS", "",
             f'GAME_VERSION = "{GAME_VERSION}"',
             f"DATA_VERSION = {DATA_VERSION}", "",
             "NORTH, SOUTH, WEST, EAST = 1, 2, 4, 8",
             "#: Each side's bit, by name.",
             'SIDE_BIT = {"north": NORTH, "south": SOUTH, "west": WEST, '
             '"east": EAST}', "", "#: Blocks full on all four sides in every "
             "state.", "WHOLE = frozenset(("]
    lines += [f'    "{name}",' for name in whole]
    lines += ["))", "", "#: Blocks with these sides full in every state.",
              "SIDES: dict[str, int] = {"]
    lines += [f'    "{name}": {mask},' for name, mask in sides.items()]
    lines += ["}", "", "#: Blocks whose sides turn on their state: the "
              "properties, then the sides for", "#: each of their values.",
              "BY_STATE: dict[str, tuple[tuple[str, ...], dict[tuple[str, ...], int]]] = {"]
    for name, (keys, table) in by_state.items():
        lines.append(f'    "{name}": ({keys!r}, {{')
        for values, mask in table.items():
            lines.append(f"        {values!r}: {mask},")
        lines.append("    }),")
    lines += ["}", "", "",
              "def full_sides(name: str, properties: dict) -> int:",
              '    """The sides of a block that are full, a mask of '
              ":data:`SIDE_BIT`: what a state",
              "    leaves unsaid is its default, and a name the game does not "
              'have has none."""',
              "    read = BY_STATE.get(name)",
              "    if read is None:",
              "        return 15 if name in WHOLE else SIDES.get(name, 0)",
              "    keys, table = read",
              "    defaults = BLOCK_DEFAULTS.get(name, {})",
              "    # a property neither given nor defaulted is \"\", which no value is",
              "    return table.get(tuple(properties.get(key, "
              "defaults.get(key, \"\")) for key in keys), 0)", ""]
    return "\n".join(lines)


def csharp_text(whole, sides, by_state) -> str:
    head = textwrap.indent(_summary(whole, sides, by_state), "//     ")
    lines = ["// <auto-generated>", head, "// </auto-generated>", "//",
             "// Twin of heaton_voxel/connect_faces.py. What a fence, a wall, "
             "a pane or iron",
             "// bars joins is a neighbor whose face toward it is full (the "
             "game's",
             "// isFaceSturdy, SupportType.FULL). Connect.cs is how it is "
             "used.", "", "#nullable enable", "", "using System;",
             "using System.Collections.Generic;", "using HeatonVoxel.Blocks;",
             "", "namespace HeatonVoxel", "{",
             "    /// <summary>Which sides of a block are full.</summary>",
             "    public static class ConnectFaces", "    {",
             "        public const int North = 1, South = 2, West = 4, "
             "East = 8;", "",
             "        private static readonly HashSet<string> Whole = new "
             "HashSet<string>(StringComparer.Ordinal)", "        {"]
    lines += [f'            "{name}",' for name in whole]
    lines += ["        };", "",
              "        private static readonly Dictionary<string, int> Sides = "
              "new Dictionary<string, int>(StringComparer.Ordinal)",
              "        {"]
    lines += [f'            {{ "{name}", {mask} }},'
              for name, mask in sides.items()]
    lines += ["        };", "",
              "        private static readonly Dictionary<string, "
              "(string[] Keys, Dictionary<string, int> Masks)> ByState =",
              "            new Dictionary<string, (string[], Dictionary<string, "
              "int>)>(StringComparer.Ordinal)", "        {"]
    for name, (keys, table) in by_state.items():
        words = ", ".join(f'"{key}"' for key in keys)
        lines.append(f'            {{ "{name}", (new[] {{ {words} }}, new '
                     f"Dictionary<string, int>(StringComparer.Ordinal)")
        lines.append("            {")
        lines += [f'                {{ "{",".join(values)}", {mask} }},'
                  for values, mask in table.items()]
        lines.append("            }) },")
    lines += ["        };", "",
              "        /// <summary>The sides of a block that are full, a mask "
              "of North, South, West",
              "        /// and East: what a state leaves unsaid is its default, "
              "and a name the game",
              "        /// does not have has none.</summary>",
              "        public static int FullSides(BlockState state)",
              "        {",
              "            if (!ByState.TryGetValue(state.Name, out var read))",
              "                return Whole.Contains(state.Name) ? 15 : "
              "Sides.TryGetValue(state.Name, out int mask) ? mask : 0;",
              "            var values = new string[read.Keys.Length];",
              "            for (int i = 0; i < values.Length; i++)",
              "                values[i] = state.GetProperty(read.Keys[i]) ?? "
              "DefaultOf(state.Name, read.Keys[i]);",
              '            return read.Masks.TryGetValue(string.Join(",", '
              "values), out int sides) ? sides : 0;",
              "        }", "",
              "        private static string DefaultOf(string name, string key)",
              "        {",
              "            foreach (var pair in "
              "BlockDefaults.DefaultProperties(name))",
              "                if (pair.Key == key)",
              "                    return pair.Value;",
              '            return "";',
              "        }", "    }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    whole, sides, by_state = tables()
    with open(PYTHON_OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(python_text(whole, sides, by_state))
    with open(CSHARP_OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(csharp_text(whole, sides, by_state))
    print(f"{len(whole)} whole, {len(sides)} some sides, {len(by_state)} by "
          f"state")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
