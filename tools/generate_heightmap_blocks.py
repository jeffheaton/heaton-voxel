#!/usr/bin/env python3
"""Write what the game's heightmaps count into both twins of the library.

A chunk stores four surface maps. ``WORLD_SURFACE`` is the topmost non-air
block, which the format alone can answer. The other three ask the game
(26.3's ``Heightmap$Types``): ``OCEAN_FLOOR`` stops at a block in the
``blocks_motion_in_heightmap`` tag, ``MOTION_BLOCKING`` at one of those or
any state that holds fluid, and ``MOTION_BLOCKING_NO_LEAVES`` at a block in
the ``blocks_motion_in_heightmap_no_leaves`` tag or any state that holds
fluid. So the lower tier needs three lists of blocks to rebuild a chunk's
maps exactly: the blocks neither tag names, the blocks only the first does
(leaves), and the blocks every state of which holds fluid. A waterlogged
state it reads off the state and the defaults table.

``tools/probe_block_shapes.py`` already reads all of that out of the jar,
into ``heaton_voxel/craft/block_facts.py`` and ``block_registry.py``, and
the lower tier may not import ``craft``, so this copies it down, into one
table per twin from the one run:

    heaton_voxel/heightmap_blocks.py
    csharp/HeatonVoxel/Blocks/HeightmapBlocks.generated.cs

Both are derived; edit neither by hand. ``heaton_voxel.blocks`` is the
reference for how the table is *used*. An old name that ``craft.blockinfo``
lists as renamed goes in beside the name it became, since a chunk the game
has not rewritten still holds it. ``tests/test_heightmaps.py`` regenerates
both files and fails if the committed ones differ, so rerun this after the
probe. It needs no game: the probe has asked already.

Usage::

    python tools/generate_heightmap_blocks.py
"""

from __future__ import annotations

import os
import sys
import textwrap

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from heaton_voxel.craft.block_facts import (  # noqa: E402
    DATA_VERSION,
    GAME_VERSION,
    in_heightmap,
)
from heaton_voxel.craft.block_registry import BLOCK_IDS, FLUIDS  # noqa: E402
from heaton_voxel.craft.blockinfo import RENAMED  # noqa: E402

PYTHON_OUT = os.path.join(REPO_ROOT, "heaton_voxel", "heightmap_blocks.py")
CSHARP_OUT = os.path.join(REPO_ROOT, "csharp", "HeatonVoxel", "Blocks",
                          "HeightmapBlocks.generated.cs")


def tables() -> tuple[list[str], list[str], list[str]]:
    """The three lists: not counted, leaves, always fluid. Sorted, an old
    name going where the name it became went."""
    not_counted = {name for name in BLOCK_IDS if not in_heightmap(name)}
    leaves = {name for name in BLOCK_IDS
              if in_heightmap(name) and not in_heightmap(name, leaves=False)}
    for old, (new, _version) in RENAMED.items():
        if new in not_counted:
            not_counted.add(old)
        if new in leaves:
            leaves.add(old)
    return sorted(not_counted), sorted(leaves), sorted(FLUIDS)


def _provenance(not_counted, leaves, fluids) -> str:
    return (f"Generated by tools/generate_heightmap_blocks.py from Minecraft "
            f"{GAME_VERSION} (DataVersion {DATA_VERSION}): {len(BLOCK_IDS)} "
            f"blocks, {len(not_counted)} names no motion-blocking heightmap "
            f"counts, {len(leaves)} leaves and {len(fluids)} always fluid. "
            f"Regenerate rather than edit; both twins are written by the "
            f"same run.")


def python_source() -> str:
    not_counted, leaves, fluids = tables()
    wrapped = textwrap.fill(_provenance(not_counted, leaves, fluids), 76)

    def listing(names) -> str:
        return "\n".join(f'    "{name}",' for name in names)

    return f'''"""What the game's heightmaps count, block by block. GENERATED.

{wrapped}

A chunk's maps stop at different blocks, and the game's tags say which:
:data:`NOT_IN_HEIGHTMAP` is what neither ``blocks_motion_in_heightmap`` tag
names, :data:`LEAVES` what only the first does, and :data:`FLUIDS` the blocks
every state of which holds fluid. :func:`heaton_voxel.blocks.heightmap_mask`
is how they are used.
"""

from __future__ import annotations

GAME_VERSION = "{GAME_VERSION}"
DATA_VERSION = {DATA_VERSION}

#: Blocks no motion-blocking heightmap counts.
NOT_IN_HEIGHTMAP = frozenset((
{listing(not_counted)}
))

#: Blocks MOTION_BLOCKING counts and MOTION_BLOCKING_NO_LEAVES does not.
LEAVES = frozenset((
{listing(leaves)}
))

#: Blocks every state of which holds fluid.
FLUIDS = frozenset((
{listing(fluids)}
))
'''


def csharp_source() -> str:
    not_counted, leaves, fluids = tables()
    wrapped = textwrap.indent(
        textwrap.fill(_provenance(not_counted, leaves, fluids), 70),
        "//     ")

    def listing(names) -> str:
        return "\n".join(f'            "{name}",' for name in names)

    return f'''// <auto-generated>
{wrapped}
// </auto-generated>
//
// Twin of heaton_voxel/heightmap_blocks.py. A chunk's maps stop at different
// blocks, and the game's tags say which: NotInHeightmap is what neither
// blocks_motion_in_heightmap tag names, Leaves what only the first does, and
// Fluids the blocks every state of which holds fluid.
// ChunkBlocks.HeightmapMask is how they are used.

using System.Collections.Generic;

namespace HeatonVoxel.Blocks
{{
    public static class HeightmapBlocks
    {{
        public const string GameVersion = "{GAME_VERSION}";
        public const int DataVersion = {DATA_VERSION};

        /// <summary>Blocks no motion-blocking heightmap counts.</summary>
        public static readonly HashSet<string> NotInHeightmap = new HashSet<string>
        {{
{listing(not_counted)}
        }};

        /// <summary>Blocks MOTION_BLOCKING counts and
        /// MOTION_BLOCKING_NO_LEAVES does not.</summary>
        public static readonly HashSet<string> Leaves = new HashSet<string>
        {{
{listing(leaves)}
        }};

        /// <summary>Blocks every state of which holds fluid.</summary>
        public static readonly HashSet<string> Fluids = new HashSet<string>
        {{
{listing(fluids)}
        }};
    }}
}}
'''


def main() -> int:
    for path, text in ((PYTHON_OUT, python_source()),
                       (CSHARP_OUT, csharp_source())):
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
